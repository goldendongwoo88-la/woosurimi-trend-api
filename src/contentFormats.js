const SD = require("./scriptDraft");
const SIG = require("./shoppingSignals");

const josa = SD.josa;

/** ① 제목형 — 가장 쉽고 가장 빠릅니다. 화면에 문구만 얹습니다. */
function 제목형(product, { problem = "", price = 0 } = {}) {
  const 문제 = problem || SD.inferProblem(product);
  const key = SD.ctaKeyword(product, 문제);
  return {
    형태: "제목형", 난이도: "하", 제작시간: "5분",
    화면: [
      { 컷: 1, 자막: `${문제}`,                                    화면: "문제 장면 (엉망인 상태)" },
      { 컷: 2, 자막: `${product}${josa(product, "으로", "로")} 해결`, 화면: "제품 등장" },
      { 컷: 3, 자막: price ? `${Number(price).toLocaleString()}원` : "가격 한 줄", 화면: "사용 장면" },
      { 컷: 4, 자막: `댓글에 "${key}"`,                            화면: "제품컷" },
    ],
    비고: "나레이션 없이 자막만. 음악은 저작권 없는 것으로.",
  };
}

/** ② 나레이션형 — 주력. 5단 대본은 scriptDraft가 만듭니다. */
function 나레이션형(product, opts = {}) {
  const d = SD.draft(product, opts);
  return { 형태: "나레이션형", 난이도: "중", 제작시간: "20분",
           대본: d.text, 줄: d.줄, 화자: d.persona.화자, 훅유형: d.hookType,
           ctaKeyword: d.ctaKeyword, needsInput: d.needsInput };
}

/**
 * ③ 사진형 — 라이브 실물(나이키 신발) 구조 그대로.
 * 사진 3장에 상단 캡션을 얹고 **마지막 장에 댓글 CTA를 박습니다.**
 * 영상 편집이 아예 없어서 제일 싸고, 인스타·스레드에 잘 맞습니다.
 */
function 사진형(product, { problem = "", angle = "" } = {}) {
  const 문제 = problem || SD.inferProblem(product);
  const key = SD.ctaKeyword(product, 문제);
  return {
    형태: "사진형", 난이도: "하", 제작시간: "10분",
    장수: 3,
    슬라이드: [
      { n: 1, 상단문구: angle || `${문제}, 이거 하나면 끝`, 사진: "제품 단독컷 (밝은 배경)" },
      { n: 2, 상단문구: "실제로 이렇게 씁니다",             사진: "사용 중인 손 컷" },
      { n: 3, 상단문구: `댓글에 '${key}' 남겨조`,           사진: "전/후 대비컷" },
    ],
    비고: "라이브 실물은 3장 구성이었고 마지막 장 자막이 댓글 유도였습니다. 문구는 사진 위에 직접 얹습니다.",
  };
}

/**
 * ④ 텍스트형(스레드) — 우리 자산과 제일 잘 붙는 형태.
 *
 * ⚠️ **2026-09-02 정정.** 우리는 "스레드는 본문에 링크를 넣을 수 있으니 전환이 가장 짧다"를
 * 전제로 삼고 있었습니다. 넣을 수 **있는** 건 맞지만, **넣으면 도달이 떨어집니다.**
 * 메타가 외부 링크가 붙은 글의 유기적 도달을 의도적으로 낮춥니다.
 *
 * 그래서 구조를 바꿉니다 — **본문에는 링크를 안 넣고, 첫 댓글에 링크를 달아 고정(Pin)합니다.**
 * 본문은 도달을 벌고 댓글이 전환을 받습니다. 링크를 본문에 두면 볼 사람 자체가 줄어
 * 전환율이 높아도 총 전환은 오히려 떨어집니다.
 *
 * 2026 알고리즘이 1순위로 보는 건 **체류시간**입니다. 그래서 본문을 짧게 끊지 않고
 * 읽히게 씁니다. 해시태그는 2~3개 — 남용은 스팸 신호입니다.
 */
function 텍스트형(product, { problem = "", price = 0, benefits = [] } = {}) {
  const 문제 = problem || SD.inferProblem(product);
  const b = benefits.length ? benefits : ["(근거 1)", "(근거 2)"];
  const 본문 = [
    `${문제} 때문에 한참 고민했는데`,
    `${product}${josa(product, "으로", "로")} 해결했거든요.`,
    ``,
    `· ${b[0]}`,
    `· ${b[1]}`,
    ...(price ? [`· ${Number(price).toLocaleString()}원`] : []),
    ``,
    `쓰면서 느낀 건 ${문제} 이게 생각보다 쉽게 없어진다는 거였어요.`,
    /** 빈 문자열은 의도한 빈 줄입니다. filter(Boolean)을 쓰면 이게 지워져 한 덩어리로 붙습니다. */
  ].filter((x) => x !== null && x !== undefined).join("\n");

  /** 링크는 여기 있습니다 — 본문이 아니라 첫 댓글입니다. 본문에 넣으면 도달이 떨어집니다. */
  const 첫댓글 = `제품은 여기 있어요 → (제휴링크)\n\n※ 이 글에는 제휴 링크가 포함되어 있고, 구매 시 일정액의 수수료를 받습니다.`;

  return { 형태: "텍스트형(스레드)", 난이도: "하", 제작시간: "5분",
           본문, 첫댓글, 해시태그권장: 2,
           글자수: 본문.replace(/\s/g, "").length,
           비고: "본문에 링크를 넣으면 메타가 도달을 낮춥니다. 링크는 **첫 댓글에 달고 고정(Pin)**하십시오. " +
                 "해시태그는 2~3개까지(남용은 스팸 신호). 대가성 문구는 링크와 같은 댓글에 둡니다." };
}

/** ⑤ 레시피형 — 조리 과정 자체가 훅입니다. 파는 건 재료가 아니라 **도구**입니다. */
function 레시피형(dish, { tool = "", secret = "" } = {}) {
  const key = SD.ctaKeyword(dish, "레시피 요리");
  return {
    형태: "레시피형", 난이도: "중", 제작시간: "30분",
    구성: [
      { 단: "훅",   내용: `${dish}, 집에서 이렇게 하면 됩니다`, 비고: "완성컷 먼저 보여주십시오" },
      { 단: "재료", 내용: "재료 3~4개만. 많으면 이탈합니다" },
      { 단: "비밀", 내용: secret || `여기에 ${"(비밀 재료 1가지)"}만 넣으면 맛이 달라집니다`, 비고: "라이브 대본이 이 장치를 썼습니다" },
      { 단: "과정", 내용: "2~3컷. 손이 나와야 합니다" },
      { 단: "CTA",  내용: `댓글에 "${key}" 남겨주세요` },
    ],
    파는것: tool || "(조리도구 — 재료보다 도구가 팔립니다)",
    비고: "레시피 자체는 저작권 보호를 거의 못 받지만, 남의 영상·사진은 쓰지 마십시오.",
  };
}

/** 소재 하나로 만들 수 있는 형태 전부. 플랫폼별로 나눠 뿌리면 중복 업로드가 아닙니다. */
function all(product, opts = {}) {
  return [제목형(product, opts), 나레이션형(product, opts), 사진형(product, opts), 텍스트형(product, opts)];
}

