/** 제목 하나를 재봅니다. */
function measure(title) {
  const t = String(title || "");
  const hit = {};
  for (const [k, d] of Object.entries(DEVICES)) hit[k] = d.test(t);
  return {
    length: t.length,
    devices: hit,
    score: Object.values(hit).filter(Boolean).length,
    max: Object.keys(DEVICES).length,
  };
}

/** AI에게 줄 지침 — 실측값을 그대로 넣습니다. */
function promptBlock() {
  return (
    `[홈판 제목 규칙 — 실측 근거]\n` +
    `일 방문 ${EVIDENCE.winner.dailyVisitors.toLocaleString()}명 블로그와 ` +
    `${EVIDENCE.baseline.dailyVisitors.toLocaleString()}명 블로그의 제목을 각 ${EVIDENCE.sampleSize}편씩 세었습니다.\n` +
    Object.values(DEVICES)
      .map((d) => `- ${d.label}: 잘 되는 쪽 ${d.winner}% / 덜 되는 쪽 ${d.baseline}%. ${d.why}\n  예) ${d.example}`)
      .join("\n") +
    `\n\n[절대 하지 말 것]\n` +
    AVOID.map((a) => `- ${a.what} — ${a.why}`).join("\n") +
    `\n\n가장 중요한 것: 궁금증은 반드시 **본문에 실제로 있는 사실**로 만드세요.\n` +
    `본문을 모르면 원래 제목에 이미 담긴 사실 안에서만 다듬으세요.\n` +
    `제목 길이는 35~45자가 적당합니다. (잘 되는 쪽 평균 41자)`
  );
}

/** 배치 지침을 프롬프트에 넣을 형태로. 글 성격을 알면 그것만, 모르면 셋 다 줍니다. */
function placementBlock(title = "", body = "") {
  const p = placementFor(title, body);
  const one = (x) =>
    `[${x.label}] 결론을 ${x.lead}에 둡니다.\n` +
    `${x.why}\n` +
    x.shape.map((s, i) => `  ${i + 1}. ${s}`).join("\n") +
    `\n주의: ${x.caution}`;

  const head =
    `\n[결론을 어디에 둘 것인가]\n` +
    `두 조언이 부딪히는 것처럼 보이지만 아닙니다. 갈라서 보세요.\n` +
    `- 판정(살까 말까, 좋다 나쁘다)은 **항상 맨 위**. 검색해서 온 사람은 답을 원하고 왔고,\n` +
    `  네이버 AI도 인용할 한 문장을 첫 문단에서 찾습니다.\n` +
    `- 반전(그 제품의 정체, 비결)은 **아래**. 홈피드로 온 사람은 궁금해서 눌렀는데\n` +
    `  첫 줄에 답이 있으면 바로 나갑니다.\n`;

  return head + "\n" + (p ? one(p) : Object.values(PLACEMENT).map(one).join("\n\n"));
}

