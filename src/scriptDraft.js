const SIG = require("./shoppingSignals");

/** 받침 여부로 조사를 고릅니다. "접시선반를"이 나오면 초안을 못 씁니다. */
function josa(word, withJong, withoutJong) {
  const c = String(word).trim().slice(-1).charCodeAt(0);
  if (c < 0xac00 || c > 0xd7a3) return withoutJong;
  return ((c - 0xac00) % 28) ? withJong : withoutJong;
}

/**
 * 댓글 CTA 키워드.
 *
 * 라이브 실제 사례는 "비누" "빵" "비밀" "청소" "원조" — 전부 **2~3자 일반명사**입니다.
 * 제품명 마지막 낱말을 그냥 쓰면 "스푼 스크러버" → "러버"처럼 아무도 안 쓸 말이 나옵니다.
 * 그래서 **쓰임새 사전을 먼저 보고**, 없을 때만 낱말을 자릅니다.
 */
const CTA사전 = [
  [/청소|세제|세정|먼지|물때|찌든때/, "청소"], [/수납|정리|선반|바구니|랙/, "정리"],
  [/비누|폼|거품|손/, "비누"],       [/곰팡이|욕실|물때/, "욕실"],
  [/주방|그릇|접시|도마|칼/, "주방"], [/빨래|세탁|건조/, "세탁"],
  [/냄새|탈취|방향/, "냄새"],        [/벌레|모기|방충/, "벌레"],
  [/커튼|시트지|인테리어|벽/, "인테리어"], [/빵|요리|레시피|조리/, "레시피"],
  [/허리|무릎|어깨|통증|자세/, "허리"], [/절약|전기|난방|냉방/, "절약"],
];
function ctaKeyword(product, context = "") {
  /**
   * ⚠️ 제품명만 보면 안 됩니다. "스푼 스크러버"에는 청소라는 말이 없어서 "스크"가 나왔습니다.
   * 사람이 댓글에 칠 말은 제품명이 아니라 **그 제품이 해결하는 일**입니다.
   * 그래서 문제 설명·카테고리까지 같이 봅니다.
   */
  const name = String(product || "");
  for (const [re, k] of CTA사전) if (re.test(name)) return k;      // 제품명이 우선
  for (const [re, k] of CTA사전) if (re.test(String(context || ""))) return k;  // 없으면 문맥
  const w = String(product || "").trim().split(/\s+/).pop() || "정보";
  return w.length <= 3 ? w : w.slice(0, 2);
}

/**
 * ── 문제 문장 사전 ──
 * 훅과 공감은 **제품이 아니라 문제**로 열어야 합니다. 라이브 대본 5편이 전부 그랬습니다.
 * 문제를 안 주면 "선풍기 청소 세제 없이 불편했던 것"처럼 아무도 안 읽는 문장이 나옵니다.
 * 제품명에서 쓰임새를 읽어 **사람이 실제로 겪는 장면**으로 바꿉니다.
 */
const 문제사전 = [
  [/선풍기|서큘레이터/,          "선풍기 날개에 먼지 뽀얗게 앉는 거"],
  [/청소|세제|세정|때|먼지/,     "청소할 때 허리 굽히는 거"],
  [/곰팡이|욕실|물때|배수구/,    "욕실 구석에 곰팡이 자꾸 올라오는 거"],
  [/수납|정리|선반|바구니|랙/,   "쓸 때마다 물건이 쏟아지는 거"],
  [/비누|폼|거품|손/,            "밖에서 남들 쓰던 공용비누 만지는 거"],
  [/냄새|탈취|방향/,             "문 열 때마다 냄새 훅 올라오는 거"],
  [/빨래|세탁|건조/,             "빨래 널 자리 없어서 여기저기 걸어두는 거"],
  [/벌레|모기|방충/,             "여름마다 벌레 들어오는 거"],
  [/커튼|시트지|벽|인테리어/,    "집이 휑해 보이는데 공사는 못 하는 거"],
  [/칼|도마|주걱|집게|주방/,     "주방 서랍에서 물건 찾느라 헤매는 거"],
  [/허리|무릎|어깨|자세|방석/,   "오래 앉아 있으면 허리 뻐근한 거"],
  [/전기|난방|냉방|절약/,        "관리비 고지서 볼 때마다 한숨 나오는 거"],
  [/거동|어르신|보조|간병/,      "어르신 혼자 움직이시기 어려운 거"],
];
function inferProblem(product) {
  const t = String(product || "");
  for (const [re, q] of 문제사전) if (re.test(t)) return q;
  return `${t} 없어서 매번 번거로운 거`;
}

/**
 * ── 5단 틀 ──
 * 자리마다 어미가 고정입니다. 이게 광고체와 후기체를 가르는 지점입니다.
 *   ① 훅     대상 지목 + 문제           "~하고 계세요?" / "~하셨던 분들"
 *   ② 공감   내 얘기로 전환              "~잖아요"
 *   ③ 발견   제3자 권위 + 반전           "~거든요"
 *   ④ 근거   스펙 2~3개                  "~니까 ~더라고요"
 *   ⑤ 마무리 완화 + 댓글 CTA             "~더라고요" + "댓글에 ○○"
 */
function draft(product, { category = "살림", problem = "", benefits = [], price = 0 } = {}) {
  const p = String(product || "").trim();
  const per = SIG.persona(category);
  const 권위 = per.권위원[0];
  const key = ctaKeyword(p, `${problem} ${category} ${benefits.join(" ")}`);
  const 문제 = problem || inferProblem(p);
  /**
   * 근거는 제품마다 다릅니다 — 이것만은 코드가 지어낼 수 없습니다.
   * 지어내면 허위광고가 되므로, 안 주면 **빈칸 표시**를 남겨 사람이 채우게 합니다.
   * 이 자리가 저장을 만드는 자리라 대충 넘기면 대본 전체가 죽습니다.
   */
  const 기본근거 = !benefits.length;
  const b = benefits.length ? benefits : ["(근거 1 — 실제로 되는 점)", "(근거 2 — 숫자나 비교)"];

  const 줄 = [];
  줄.push({ 단: "① 훅", 문장: `${문제}, 아직 그냥 참고 계세요?`,
            메모: "0~3초. 대상을 지목하고 문제를 던집니다. 정리된 화면 말고 엉망인 화면으로 여십시오" });
  줄.push({ 단: "② 공감", 문장: `${문제} 진짜 은근히 신경 쓰이잖아요.`,
            메모: `"~잖아요"로 내 얘기가 되게 만듭니다. 화자는 ${per.화자}입니다` });
  줄.push({ 단: "③ 발견", 문장: `${권위}${josa(권위, "이", "가")} 알려줘서 ${p}${josa(p, "을", "를")} 써봤는데 이건 좀 다르거든요.`,
            메모: `제3자 권위 — 브랜드 말고 사람입니다. 연차를 붙이면 더 셉니다(예: "30년차 ${권위}")` });
  줄.push({ 단: "④ 근거", 문장: `${b[0]}, ${b[1] || "관리도 편하다"}${b[1] ? "" : ""}는 게 제일 좋더라고요.`,
            메모: "여기가 저장을 만듭니다. 숫자·비교를 넣고 손이 나오는 화면으로" });
  if (price) 줄.push({ 단: "④-2 가격", 문장: `${Number(price).toLocaleString()}원인데 이 정도면 안 살 이유가 없죠.`,
            메모: "가격은 화면에도 박습니다" });
  줄.push({ 단: "⑤ 마무리", 문장: `이런 거 하나 있으면 확실히 덜 번거롭더라고요. 궁금하신 분들 댓글에 ${key} 남겨주세요.`,
            메모: `링크 유도보다 저항이 낮고 댓글이 알고리즘에 실립니다. 대가성 문구는 설명란 첫 줄` });

  const text = 줄.map((r) => r.문장).join(" ");
  return { product: p, category, persona: per, ctaKeyword: key, 줄, text,
           needsInput: 기본근거 ? ["④ 근거 2개 — 제품 상세에서 가져와 채우십시오. 지어내면 허위광고입니다"] : [] };
}

module.exports = { draft, ctaKeyword, inferProblem, josa };
