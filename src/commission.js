/**
 * 쿠팡 파트너스 — 카테고리별 상한 (공개 자료 기준, 2026-09)
 *
 * ⚠️ **순서가 곧 우선순위입니다.** 처음엔 생활용품을 위에 뒀더니 `세탁` 패턴이
 * "삼성 드럼세탁기"를 먼저 먹어서 가전(1%)이 생활용품(2%)으로 분류됐습니다.
 * 요율이 두 배로 부풀면 소재 선정이 통째로 틀어집니다.
 * **구체적인 완제품(가전)을 먼저, 넓은 소모품(생활)을 나중에** 둡니다.
 */
const 쿠팡요율 = [
  { re: /뷰티|화장품|스킨케어|섀도우|틴트|앰플|세럼|마스크팩|화장솜/, rate: 0.03, 군: "뷰티" },
  { re: /패션|의류|상의|하의|아우터|신발|가방|잡화|옷걸이|보풀/,      rate: 0.03, 군: "패션잡화" },
  { re: /스포츠|레저|운동|헬스|등산|캠핑|골프|낚시/,                  rate: 0.03, 군: "스포츠레저" },
  { re: /출산|육아|아기|유아|기저귀|이유식|젖병/,                     rate: 0.03, 군: "출산육아" },
  { re: /도서|음반|책/,                                              rate: 0.03, 군: "도서음반" },
  // ── 가전을 먼저 겁니다 (아래 '생활용품'의 넓은 패턴에 먹히지 않도록) ──
  { re: /가전|디지털|전자제품|세탁기|건조기|냉장고|워시타워|TV|노트북|모니터|에어컨|제습기|공기청정|청소기|워치|스마트폰|태블릿|이어폰/,
    rate: 0.01, 군: "가전디지털" },
  { re: /식품|건강|영양제|콜라겐|유산균|간편식|반찬|김치|즙|차/,   rate: 0.02, 군: "식품건강" },
  { re: /생활|주방|청소|세제|수납|정리|선반|욕실|침구|세탁|빨래|탈취|밀폐|위생|트레이|커버|망|호일|장갑/,
    rate: 0.02, 군: "생활용품" },
];
const 쿠팡기본 = 0.02;

/**
 * 유튜브 쇼핑 제휴 — 2026년의 가장 큰 기회.
 *
 * 업계 평균으로 **패션·뷰티 5~15%, 전자제품 2~5%**. 쿠팡(3% 상한)의 2~5배입니다.
 * 조건도 낮아졌습니다 — 2026-03-30부터 **구독자 500명**이면 됩니다.
 * 한국은 2025년 하반기 정식 지원, 올리브영·컬리·오늘의집 등 10개사가 붙었습니다.
 *
 * ⚠️ 브랜드마다 요율이 달라 **보수적으로 하한을 씁니다.** 지어낸 숫자로 기대를 부풀리면
 * 소재 선정이 통째로 틀어집니다.
 */
const 유튜브쇼핑요율 = [
  { re: /뷰티|화장품|스킨케어|패션|의류|상의|하의|신발/, low: 0.05, high: 0.15, 군: "패션뷰티" },
  { re: /가전|디지털|전자/,                              low: 0.02, high: 0.05, 군: "전자제품" },
];

const 제휴처정보 = {
  "쿠팡 파트너스": { 상태: "연동됨", 쿠키: "클릭 후 24시간", 근거: "공개 요율표 2곳 교차확인" },
  "유튜브 쇼핑":   { 상태: "미가입", 조건: "구독자 500명 + YPP(쇼츠 조회수 300만 또는 시청 3,000시간)", 근거: "업계 평균, 브랜드별 상이" },
  "토스":         { 상태: "미가입", 근거: "돈농부 라이브 발언(판매금액 10%) — 미검증" },
};

const match = (table, product, dflt) => {
  const t = String(product || "");
  for (const r of table) if (r.re.test(t)) return r;
  return dflt;
};

/** 쿠팡에서 이 제품의 수수료율. */
function coupangRate(product) {
  const hit = match(쿠팡요율, product, null);
  return hit ? { rate: hit.rate, 군: hit.군 } : { rate: 쿠팡기본, 군: "미분류(기본 2% 가정)" };
}

/**
 * 제품 + 가격 → 어디로 보내는 게 유리한가.
 * 가입 안 된 곳은 **기대치만 보여주고 '미가입'으로 표시**합니다. 지어내지 않습니다.
 */
function bestRoute(product, price = 0) {
  const p = Number(price) || 0;
  const c = coupangRate(product);
  const rows = [{
    제휴처: "쿠팡 파트너스", 요율: `${(c.rate * 100).toFixed(0)}%`, 군: c.군,
    건당: p ? Math.round(p * c.rate) : null, 상태: "연동됨",
  }];
  const y = match(유튜브쇼핑요율, product, null);
  if (y) rows.push({
    제휴처: "유튜브 쇼핑", 요율: `${(y.low * 100).toFixed(0)}~${(y.high * 100).toFixed(0)}%`, 군: y.군,
    건당: p ? Math.round(p * y.low) : null, 상태: "미가입 — 구독자 500명 필요",
    비고: `쿠팡 대비 최소 ${(y.low / c.rate).toFixed(1)}배`,
  });
  /**
   * 가격을 모를 때가 많습니다(쿠팡 키가 없으면 전부 0). 그때 건당 금액으로 정렬하면
   * 전부 0이라 **입력 순서가 그대로 답이 되어버립니다.** 가격이 없으면 요율로 정렬합니다.
   */
  const 요율값 = (r) => Number(String(r.요율).match(/[\d.]+/)?.[0] || 0);
  rows.sort((a, b) => (p ? (b.건당 || 0) - (a.건당 || 0) : 요율값(b) - 요율값(a)));
  return { 제품: product, 가격: p, 경로: rows, 추천: rows[0] };
}

/**
 * 수수료축 점수 — 구매력 점수에 곱해 쓸 배율.
 * 뷰티 3% vs 가전 1%가 3배 차이인데 지금까지 이걸 안 보고 있었습니다.
 */
function commissionMultiplier(product) {
  const c = coupangRate(product);
  return { mult: +(c.rate / 쿠팡기본).toFixed(2), 요율: c.rate, 군: c.군 };
}

/**
 * ⚠️ 실효 수수료는 요율표보다 훨씬 낮습니다.
 * 공개된 실측: **거래액 400만원 → 수익 8만원 (2% 미만)**.
 * 클릭한 제품이 아닌 딴 물건이 팔리고, 그게 대개 저요율이기 때문입니다.
 * 기대수익을 계산할 때 이 값을 곱해 **부풀리지 않습니다.**
 */
const 실효계수 = 0.7;
const expectedRevenue = (price, product, 전환수 = 1) =>
  Math.round((Number(price) || 0) * coupangRate(product).rate * 실효계수 * 전환수);

module.exports = { coupangRate, bestRoute, commissionMultiplier, expectedRevenue,
                   쿠팡요율, 유튜브쇼핑요율, 제휴처정보, 실효계수 };
