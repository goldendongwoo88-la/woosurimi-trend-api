const SIG = require("./shoppingSignals");
let TREND = null;
try { TREND = require("./trendSource"); } catch { /* 없으면 시즌만으로 갑니다 */ }

/**
 * 붙일 수 있는 이슈인가.
 *
 * 먼저 **절대 붙이면 안 되는 것**부터 겁니다. 순서가 중요합니다 —
 * "사고"가 들어간 이슈에 제품을 붙이는 건 돈 문제가 아니라 사람 문제입니다.
 */
const 금지 = [
  { re: /사망|사고|참사|화재|지진|침몰|추락|실종|부고|빈소|장례/, 왜: "사건·사고 — 제품을 붙이면 안 됩니다" },
  { re: /검찰|수사|기소|재판|구속|국회|대통령|장관|정당|선거|의혹|논란|고발/, 왜: "정치·수사 — 구매로 이어지지 않고 계정만 시끄러워집니다" },
  { re: /확진|감염|백신|질병|암\s|사망률/, 왜: "질병 — 의료 오인 소지" },
  { re: /주가|코인|환율|금리|상장|공모주/, 왜: "투자 — 우리 영역이 아닙니다" },
];

/** 붙일 수 있는 것 — 소비로 이어지는 영역만. */
const 결합가능 = [
  { re: /요리|레시피|맛집|먹방|셰프|백종원|흑백요리사|edible/, 카테고리: "간편식", 각도: "그 요리를 집에서 하는 도구" },
  { re: /드라마|예능|넷플릭스|시리즈|방영|OTT/,                카테고리: "간편식", 각도: "그거 보면서 먹는 것 / 나온 소품 비슷한 것" },
  { re: /캠핑|여행|공항|휴가|숙소|나들이/,                      카테고리: "여행용품", 각도: "챙겨가면 편한 것" },
  { re: /운동|헬스|러닝|다이어트|마라톤|등산/,                  카테고리: "운동용품", 각도: "초보가 처음 사는 것" },
  { re: /추석|설날|명절|크리스마스|연말|새해/,                  카테고리: "선물",     각도: "부담 없는 선물 / 명절 뒷정리" },
  { re: /폭염|한파|장마|태풍|미세먼지|황사|환절기|더위|추위/,   카테고리: "계절가전", 각도: "그 날씨를 견디는 물건" },
  { re: /개학|입학|졸업|시험|수능|이사|자취/,                   카테고리: "생활",     각도: "그 시기에 새로 사는 것" },
  { re: /반려|강아지|고양이|펫/,                                카테고리: "반려용품", 각도: "키우면 결국 사는 것" },
];

function 판정(term) {
  const t = String(term || "");
  for (const g of 금지) if (g.re.test(t)) return { 결합가능: false, 사유: g.왜 };
  for (const c of 결합가능) if (c.re.test(t)) return { 결합가능: true, ...c };
  return { 결합가능: false, 사유: "쇼핑과 연결점이 안 보입니다" };
}

/**
 * 오늘 결합할 수 있는 이슈를 고릅니다.
 * @returns {{쓸수있음:Array, 버린것:Array, 시즌:Object, note:string}}
 */
async function todayCombos({ month = null, limit = 20 } = {}) {
  const 시즌 = SIG.시즌배율(month);
  let terms = [];
  const warnings = [];

  if (TREND) {
    try {
      const r = await TREND.fetchGoogleTrendsKR();
      terms = (r.items || []).slice(0, limit).map((x) => ({ term: x.term, rank: x.rank, traffic: x.approxTraffic }));
    } catch (e) { warnings.push(`구글 트렌드 실패: ${e.message}`); }
  } else warnings.push("trendSource 없음 — 시즌만으로 갑니다");

  const 쓸수있음 = [], 버린것 = [];
  for (const t of terms) {
    const v = 판정(t.term);
    if (v.결합가능) {
      const bp = SIG.buyingPower(v.카테고리, { month });
      쓸수있음.push({ 이슈: t.term, 순위: t.rank, 카테고리: v.카테고리, 각도: v.각도, 구매력: bp.mult });
    } else 버린것.push({ 이슈: t.term, 순위: t.rank, 사유: v.사유 });
  }

  /** 이슈가 하나도 안 걸려도 **시즌은 늘 있습니다.** 빈손으로 돌려보내지 않습니다. */
  const 시즌소재 = (시즌.소재 || []).map((s) => ({
    이슈: `${시즌.이름} (시즌)`, 순위: null, 카테고리: s, 각도: "지금 시기에 사람들이 찾는 것", 구매력: 시즌.v,
  }));

  return {
    쓸수있음: 쓸수있음.sort((a, b) => b.구매력 - a.구매력),
    시즌소재, 버린것, 시즌, warnings,
    note: 쓸수있음.length
      ? `트렌드 ${terms.length}건 중 ${쓸수있음.length}건이 결합 가능합니다.`
      : `트렌드 ${terms.length}건 중 결합 가능한 게 없습니다. 정상입니다 — 대부분의 이슈는 쇼핑에 못 붙습니다. 시즌 소재로 가십시오.`,
  };
}

module.exports = { todayCombos, 판정, 금지, 결합가능 };
