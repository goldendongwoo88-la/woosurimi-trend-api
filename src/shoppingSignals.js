  const p = 단가배율(price, { 어트리뷰션: attr });
  const g = pick(관여도배율, text);
  const s = 시즌배율(month);
  /**
   * 수수료축 (2026-09-02 추가).
   * 공개 요율표를 찾아보니 뷰티 3% · 생활 2% · **가전 1%** 로 3배가 갈립니다.
   * 지금까지 이 축이 아예 없어서, 같은 조회수·같은 단가면 같은 점수로 봤습니다.
   * 실제로는 뷰티가 가전의 3배입니다.
   */
  const c = COM ? COM.commissionMultiplier(product) : { mult: 1.0, 군: "수수료 모듈 없음", 요율: null };
